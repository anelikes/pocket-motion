#!/usr/bin/env bun
/**
 * Render the capability catalog from `src/catalog/surface.ts`.
 *
 *   bun scripts/catalog.ts --write   write CAPABILITIES.md
 *   bun scripts/catalog.ts --check   exit 1 if the file on disk is stale
 *   bun scripts/catalog.ts           same as --check
 *
 * The file is byte-identical on any machine: SURFACE order, sorted
 * diagnostics, no timestamp, no host path, no version string.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { SURFACE, type CapabilityRow } from "../src/catalog/surface.ts";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const CATALOG_PATH = join(ROOT, "CAPABILITIES.md");

const GROUP_HEADINGS: Record<CapabilityRow["group"], string> = {
  sidecar: "Sidecar root (`pocket-motion.json`)",
  footage: "Footage (`pocket-motion.json` `footage[]`)",
  fonts: "Fonts (`pocket-motion.json` `fonts`)",
  sound: "Sound (`pocket-motion.json` `sound`)",
  assets: "Assets (discovered, not declared)",
  animation: "Animation (`pocket.config.ts` theme + class literals)",
  declare: "Declaring footage (generator side — `src/footage/declare.ts`)",
  output: "Output (`render` flags — nothing here moves a pixel)",
  layout: "Layout findings (`layout --json` `findings[]`)",
};

const GROUP_ORDER: readonly CapabilityRow["group"][] = [
  "sidecar",
  "footage",
  "fonts",
  "sound",
  "assets",
  "animation",
  "declare",
  "output",
  "layout",
];

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|");
}

function requiredCell(required: boolean): string {
  return required ? "yes" : "no";
}

function defaultCell(value: string | null): string {
  return value === null ? "—" : escapeCell(value);
}

function renderTable(rows: readonly CapabilityRow[]): string {
  const lines = [
    "| key | required | default | constraint | source | verified |",
    "|---|---|---|---|---|---|",
  ];
  for (const row of rows) {
    lines.push(
      `| ${escapeCell(row.key)} | ${requiredCell(row.required)} | ${defaultCell(row.defaultValue)} | ${escapeCell(row.constraint)} | ${escapeCell(row.source)} | ${row.verification} |`,
    );
  }
  return lines.join("\n");
}

function renderDiagnostics(): string {
  const owned: { code: string; id: string }[] = [];
  for (const row of SURFACE) {
    for (const code of row.diagnostics) {
      owned.push({ code, id: row.id });
    }
  }
  owned.sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : a.id < b.id ? -1 : 0));
  const lines = [
    "| code | row |",
    "|---|---|",
    ...owned.map((entry) => `| ${escapeCell(entry.code)} | ${escapeCell(entry.id)} |`),
  ];
  return lines.join("\n");
}

/** Deterministic markdown for `CAPABILITIES.md`. */
export function renderCatalog(): string {
  const sections: string[] = [
    "<!-- generated by `bun scripts/catalog.ts --write`; do not edit -->",
    "",
    "# Capability catalog",
    "",
    "Every input a composition can declare, and every input the build discovers without being told.",
    "Generated from `src/catalog/surface.ts` and the constants in `src/manifest/sidecar.ts`; each row's",
    "`verified` column states how far this repository has actually checked it — `probed` means a",
    "violation was constructed and the implementation rejected it, `pinned` means the stated literal was",
    "found in the named source file and nothing more.",
    "",
    "Sidecar rows are probed against `parseSidecar` and name the diagnostic they produce. Animation",
    "rows are probed against the vendored compiler, which has no diagnostic codes and refuses by",
    "throwing, so those rows own none. Layout findings are neither: they are read off a rendered",
    "frame, own no diagnostics, and are probed by handing `findingsFor` a geometry copied out of",
    "`compositions/layout-codes` and asserting the codes it returns.",
  ];

  for (const group of GROUP_ORDER) {
    const rows = SURFACE.filter((row) => row.group === group);
    if (rows.length === 0) continue;
    sections.push("", `## ${GROUP_HEADINGS[group]}`, "", renderTable(rows));
  }

  sections.push("", "## Diagnostics", "", renderDiagnostics(), "");
  return sections.join("\n");
}

/** Unified-style hunk covering the first differing region. */
export function firstDifferingHunk(disk: string, generated: string): string {
  const a = disk.split("\n");
  const b = generated.split("\n");
  const n = Math.max(a.length, b.length);
  let i = 0;
  while (i < n && a[i] === b[i]) i++;
  if (i === n) return "";
  const ctx = 3;
  const start = Math.max(0, i - ctx);
  const end = Math.min(n, i + ctx + 1);
  const lines = [
    "--- CAPABILITIES.md",
    "+++ generated",
    `@@ -${start + 1},${end - start} +${start + 1},${end - start} @@`,
  ];
  for (let j = start; j < end; j++) {
    const left = a[j];
    const right = b[j];
    if (left === right) {
      lines.push(` ${left ?? ""}`);
    } else {
      if (left !== undefined) lines.push(`-${left}`);
      if (right !== undefined) lines.push(`+${right}`);
    }
  }
  return lines.join("\n");
}

function main(argv: readonly string[]): number {
  const write = argv.includes("--write");
  const generated = renderCatalog();
  if (write) {
    writeFileSync(CATALOG_PATH, generated);
    process.stdout.write(`wrote ${CATALOG_PATH}\n`);
    return 0;
  }
  if (!existsSync(CATALOG_PATH)) {
    process.stderr.write("CAPABILITIES.md is missing; run `bun scripts/catalog.ts --write`\n");
    return 1;
  }
  const disk = readFileSync(CATALOG_PATH, "utf8");
  if (disk === generated) return 0;
  process.stderr.write("CAPABILITIES.md is not current. First differing region:\n");
  process.stderr.write(firstDifferingHunk(disk, generated));
  process.stderr.write("\n");
  return 1;
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2)));
}
