#!/usr/bin/env bun
/**
 * Writes the sixty covers `compositions/image-wall` draws, the `app.tsx`
 * that lays them out, and the `images.json` that stores them as RGB565.
 * `.gitignore` ignores `*.png`, so
 * the pictures are made here, from integer arithmetic and `Math.sqrt`
 * (correctly rounded), and the ledger and the tests run this before they
 * build (`src/cli/generators.ts`).
 *
 * Each cover is 300x420 and carries the detail a poster or an album cover
 * carries and a wall drawn at 15% cannot show: rings 3 to 6 px apart, rows of
 * 2 px bars standing for a title, a 1 px checker and a 2 px frame. At 45 px
 * wide every one of them is finer than a pixel, which is what aliases.
 *
 *   bun compositions/image-wall/gen.ts
 */

import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { pocketjsRoot } from "../../src/runtime/boot.ts";

const DIR = fileURLToPath(new URL(".", import.meta.url));
const { encodePNG } = (await import(`${pocketjsRoot()}/tests/png.ts`)) as {
  encodePNG: (rgba: Uint8Array, w: number, h: number) => Buffer;
};

export const COVERS = 60;
export const COVER_W = 300;
export const COVER_H = 420;

/** Twelve grounds, two tones each (top, bottom). */
const GROUNDS: readonly [number, number, number, number, number, number][] = [
  [212, 64, 52, 120, 20, 30], [32, 96, 180, 10, 30, 80], [240, 196, 60, 180, 90, 20],
  [40, 150, 110, 10, 60, 50], [130, 60, 170, 50, 20, 90], [230, 120, 150, 120, 40, 70],
  [60, 70, 80, 15, 18, 24], [250, 240, 220, 190, 170, 140], [20, 160, 190, 0, 70, 100],
  [200, 90, 40, 90, 30, 10], [90, 170, 60, 30, 80, 20], [170, 180, 200, 80, 90, 120],
];

/** xorshift32, seeded per cover. */
function rng(seed: number): () => number {
  let s = seed >>> 0 || 1;
  return () => {
    s ^= s << 13; s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5; s >>>= 0;
    return s;
  };
}

export function cover(i: number): Uint8Array {
  const w = COVER_W, h = COVER_H;
  const rgba = new Uint8Array(w * h * 4);
  const [r0, g0, b0, r1, g1, b1] = GROUNDS[i % GROUNDS.length]!;
  const next = rng(0x9e3779b9 ^ (i * 0x85ebca6b));
  const period = 3 + (i % 4);
  const cx = 60 + (next() % 180), cy = 70 + (next() % 160);
  // A title: four rows of bars, each row a run of "words".
  const words: [number, number, number][] = [];
  for (let row = 0; row < 4; row++) {
    let x = 24;
    while (x < w - 40) {
      const len = 12 + (next() % 40);
      words.push([x, Math.min(x + len, w - 24), 300 + row * 18]);
      x += len + 6 + (next() % 6);
    }
  }
  const ink = (i * 7) % 2 === 0 ? [250, 250, 245] : [16, 16, 20];
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const o = (y * w + x) * 4;
      let r = Math.round(r0 + ((r1 - r0) * y) / (h - 1));
      let g = Math.round(g0 + ((g1 - g0) * y) / (h - 1));
      let b = Math.round(b0 + ((b1 - b0) * y) / (h - 1));
      const dx = x - cx, dy = y - cy;
      const ring = Math.floor(Math.sqrt(dx * dx + dy * dy) / period);
      if (y < 280 && ring < 40 && ring % 2 === 0) {
        r = 255 - r; g = 255 - g; b = 255 - b;
      }
      for (const [xa, xb, top] of words) {
        if (x >= xa && x < xb && y >= top && y < top + 12 && (y - top) % 3 !== 2) {
          [r, g, b] = ink as [number, number, number];
        }
      }
      if (x >= w - 64 && x < w - 16 && y >= 16 && y < 64 && (x + y) % 2 === 0) {
        r = 255; g = 255; b = 255;
      }
      if (x < 2 || y < 2 || x >= w - 2 || y >= h - 2) {
        r = 255; g = 255; b = 255;
      }
      rgba[o] = r; rgba[o + 1] = g; rgba[o + 2] = b; rgba[o + 3] = 255;
    }
  }
  return rgba;
}

export const coverName = (i: number) => `cover-${String(i).padStart(2, "0")}.png`;

/** Drawn size: 15% of the cover, so 6.67 texels a pixel before the push. */
export const DRAWN_W = 45;
export const DRAWN_H = 63;
export const COLS = 12;
export const GAP = 9;

/** `filter` is the class an image carries: the fixture's, or none for the
 *  comparisons `baselines/image-wall/shimmer.ts` renders. */
export function source(filter = " image-filter-trilinear"): string {
  const rows: string[] = [];
  for (let r = 0; r < COVERS / COLS; r++) {
    const cells: string[] = [];
    for (let c = 0; c < COLS; c++) {
      const name = coverName(r * COLS + c);
      cells.push(
        `          <Image debugName="${name.slice(0, -4)}" class="w-[${DRAWN_W}px] h-[${DRAWN_H}px]${filter}" src="${name}" />`,
      );
    }
    rows.push(`        <View class="flex-row gap-[${GAP}px]">\n${cells.join("\n")}\n        </View>`);
  }
  const w = COLS * DRAWN_W + (COLS - 1) * GAP;
  const h = (COVERS / COLS) * DRAWN_H + (COVERS / COLS - 1) * GAP;
  return `// GENERATED by compositions/image-wall/gen.ts — do not edit.
//
// Sixty 300x420 covers drawn at ${DRAWN_W}x${DRAWN_H}, and the wall pushed in from 1x to 1.75x
// over ten seconds: 6.67 texels a pixel at the first frame, 3.81 at the last,
// crossing from levels 2 and 3 to levels 1 and 2 at 4.

import { Image, View } from "@pocketjs/framework/components";

export default function Wall() {
  return (
    <View class="w-full h-full bg-[#101014]">
      <View class="absolute left-[${(1280 - w) >> 1}px] top-[${(720 - h) >> 1}px] w-[${w}px] h-[${h}px] flex-col gap-[${GAP}px] origin-center animate-push">
${rows.join("\n")}
      </View>
    </View>
  );
}
`;
}

/**
 * A copy of this composition at `dist/image-wall-<name>` — two levels down,
 * where `repoRootOf` reads the repository root as it does for a staged job —
 * whose images carry `filter` and, with `linear`, `images.json`'s bilinear
 * flag. The covers must already be written. What `tests/image-wall.test.ts`
 * and `baselines/image-wall/shimmer.ts` compare the fixture against.
 */
export async function stageVariant(
  name: string,
  opts: { filter: string; linear: boolean },
): Promise<{ dir: string; dispose: () => Promise<void> }> {
  const root = join(DIR, "..", "..");
  const dir = join(root, "dist", `image-wall-${name}`);
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
  await cp(DIR, dir, { recursive: true, filter: (src) => !src.endsWith("gen.ts") });
  await writeFile(join(dir, "app.tsx"), source(opts.filter));
  const images: Record<string, object> = {};
  for (let i = 0; i < COVERS; i++) images[coverName(i)] = { psm: 0, ...(opts.linear ? { linear: true } : {}) };
  await writeFile(join(dir, "images.json"), JSON.stringify(images, null, 2));
  const pocket = JSON.parse(await readFile(join(dir, "pocket.json"), "utf8"));
  pocket.app.entry = relative(root, join(dir, "main.tsx"));
  await writeFile(join(dir, "pocket.json"), JSON.stringify(pocket, null, 2));
  const config = await readFile(join(dir, "pocket.config.ts"), "utf8");
  const vendor = relative(dir, join(root, "vendor", "pocketjs", "framework", "src", "config.ts"));
  await writeFile(join(dir, "pocket.config.ts"), config.replace(/"[^"]*framework\/src\/config\.ts"/, JSON.stringify(vendor)));
  return { dir, dispose: () => rm(dir, { recursive: true, force: true }) };
}

if (import.meta.main) {
  const images: Record<string, { psm: number }> = {};
  for (let i = 0; i < COVERS; i++) {
    await Bun.write(join(DIR, coverName(i)), encodePNG(cover(i), COVER_W, COVER_H));
    // PSM_5650: opaque covers at two bytes a texel, 15 MB of pak instead of 30.
    images[coverName(i)] = { psm: 0 };
  }
  await Bun.write(join(DIR, "images.json"), JSON.stringify(images, null, 2) + "\n");
  await Bun.write(join(DIR, "app.tsx"), source());
}
