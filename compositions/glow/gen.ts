#!/usr/bin/env bun
/**
 * A white 取消 button on a dark ground, with a glow plate baked at build
 * time. The renderer has no blur; `src/image/glow.ts` writes the falloff
 * into glow.png and this file writes the tree that paints it first.
 *
 *   bun compositions/glow/gen.ts
 *   bun src/cli/main.ts render compositions/glow --out out.mp4
 */

import { mkdir } from "node:fs/promises";
import { join, resolve } from "node:path";

import { CANCEL_BUTTON, GLOW_ASSET, rasterGlowPlate, writeGlowPng } from "../../src/image/glow.ts";

const DIR = new URL(".", import.meta.url).pathname;

export function source(plate: { width: number; height: number }): string {
  const b = CANCEL_BUTTON;
  return `// GENERATED by compositions/glow/gen.ts — do not edit.
//
// The glow Image is painted first; the button sits on top. Sizes come from
// the plate raster so the UV mapping is 1:1 with the pow2 canvas.

import { Image, Text, View } from "@pocketjs/framework/components";

export default function Glow() {
  return (
    <View class="w-full h-full bg-[#0a0c10] items-center justify-center">
      <View class="relative w-[${plate.width}px] h-[${plate.height}px] items-center justify-center">
        <Image debugName="glow" class="absolute left-0 top-0 w-[${plate.width}px] h-[${plate.height}px]" src="${GLOW_ASSET}" />
        <View class="w-[${b.width}px] h-[${b.height}px] rounded-[${b.radius}px] bg-[#f4f4f5] items-center justify-center">
          <Text class="text-[28px] text-[#111827]">{${JSON.stringify("取消")}}</Text>
        </View>
      </View>
    </View>
  );
}
`;
}

export async function generate(outDir: string = DIR): Promise<void> {
  const dest = join(outDir, GLOW_ASSET);
  const plate = await writeGlowPng(dest, CANCEL_BUTTON);
  await Bun.write(join(outDir, "app.tsx"), source(plate));
}

if (import.meta.main) {
  const outDir = resolve(DIR);
  await mkdir(outDir, { recursive: true });
  await generate(outDir);
  const plate = rasterGlowPlate(CANCEL_BUTTON);
  console.log(`glow: wrote ${join(outDir, "app.tsx")} and ${GLOW_ASSET} (${plate.width}×${plate.height})`);
}
