#!/usr/bin/env bun
/**
 * Generate the minification probe's `app.tsx`.
 *
 * A `cols`x`rows` grid of footage tiles, each drawn at `cell` px. A tile is a
 * 512px texture but only DRAWS its interior (`INTERIOR`, 510) — the texels
 * either side are the neighbour's, so bilinear can cross the join (tiling.ts).
 * The minification ratio the rasteriser is asked for is therefore
 * `INTERIOR / cell`, and that ratio is the only thing the probe varies: the
 * picture, its position and the ground are the same in every run.
 *
 * The grid is centred in a 1920x1080 viewport, so the drawn picture must fit —
 * `cols * cell <= 1920` and `rows * cell <= 1080`.
 *
 *   bun compositions/shimmer/gen.ts 4 2 255     # 4x2 tiles at 255 -> 2x
 *   bun compositions/shimmer/gen.ts 2 1 510     # 2x1 tiles at 510 -> 1:1
 *
 * The ingest sizes the probe uses are exact multiples of INTERIOR, so every
 * tile is square and full and the grid stays uniform.
 */

import { interiorOf } from "../../src/footage/tiling.ts";

export const VIEW = { w: 1920, h: 1080 } as const;
export const TILE = 512;
export const INTERIOR = interiorOf(TILE);

export interface Layout {
  readonly cols: number;
  readonly rows: number;
  readonly cell: number;
}

/** Where the drawn picture lands, centred and pinned to even pixels. */
export function rect(l: Layout): { x: number; y: number; w: number; h: number } {
  const w = l.cols * l.cell;
  const h = l.rows * l.cell;
  if (w > VIEW.w || h > VIEW.h) {
    throw new Error(`shimmer: ${w}x${h} does not fit in ${VIEW.w}x${VIEW.h}`);
  }
  return { x: ((VIEW.w - w) >> 1) & ~1, y: ((VIEW.h - h) >> 1) & ~1, w, h };
}

/** INTERIOR / cell — how much the rasteriser has to shrink each tile. */
export const ratio = (l: Layout): number => INTERIOR / l.cell;

export function source(l: Layout): string {
  const r = rect(l);
  const tiles: string[] = [];
  for (let row = 0; row < l.rows; row++) {
    for (let col = 0; col < l.cols; col++) {
      tiles.push(
        `      <Image debugName="footage:probe/tile:${col}:${row}" ` +
          `class="absolute w-[${l.cell}] h-[${l.cell}] ` +
          `top-[${r.y + row * l.cell}] left-[${r.x + col * l.cell}]" />`,
      );
    }
  }

  const r0 = ratio(l);
  const how =
    r0 === 1
      ? "native size, so the rasteriser does no resampling — the control"
      : r0 > 1
        ? `1/${r0.toFixed(2)} size, so the rasteriser minifies ${r0.toFixed(2)}x`
        : `${(1 / r0).toFixed(2)}x size, so the rasteriser magnifies ${(1 / r0).toFixed(2)}x`;

  return `// GENERATED by compositions/shimmer/gen.ts — ${l.cols}x${l.rows} at ${l.cell}. Do not edit.
//
// ${l.cols}x${l.rows} tiles of ${INTERIOR} drawn pixels (in ${TILE}px textures) at
// ${l.cell}px: a ${r.w}x${r.h} picture at
// ${how}.
//
// Nothing else is on screen and the ground is pure black, so the probe rectangle
// holds only resampled footage and can be compared against a reference downscale
// of the same source.
//
// Mount-only: the guest declares the placeholders and never touches them. The
// host swaps their pixels (src/footage/layer.ts).

import { Image, View } from "@pocketjs/framework/components";

export default function Shimmer() {
  return (
    <View class="w-full h-full bg-black">
${tiles.join("\n")}
    </View>
  );
}
`;
}

if (import.meta.main) {
  const args = process.argv.slice(2, 5).map(Number);
  if (args.length !== 3 || !args.every((n) => Number.isInteger(n) && n > 0)) {
    console.error("usage: gen.ts <cols> <rows> <cell>");
    process.exit(2);
  }
  const [cols, rows, cell] = args as [number, number, number];
  const l: Layout = { cols, rows, cell };
  await Bun.write(new URL("./app.tsx", import.meta.url).pathname, source(l));
  console.log(`shimmer: ${l.cols}x${l.rows} tiles of ${TILE} at ${l.cell} — ${ratio(l).toFixed(2)}x`);
}
