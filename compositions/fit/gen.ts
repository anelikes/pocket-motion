#!/usr/bin/env bun
/**
 * Generate the text-fitting probe's `app.tsx` from a JSON spec.
 *
 * The probe drives this repeatedly with different specs, so the spec is a file
 * path rather than positional arguments (`scripts/fit-probe.ts`). Every block is
 * a fixed `w x h` box stacked from the top-left with no padding and no gap, so
 * a block's band in the rendered frame is known arithmetic — `bands()` — and
 * the frame can be scanned for ink outside the box without asking the layout
 * where anything went.
 *
 * Ground is pure black and text is pure white, so "ink" is any non-black pixel.
 * A block can instead be filled white with no text, which renders its box
 * exactly: that variant is how the probe checks the band arithmetic against the
 * layout rather than trusting it.
 *
 * The viewport is tall rather than 1080 because the probe stacks a few dozen
 * blocks in one build and the logical viewport is just the size the core is
 * booted at (`src/runtime/boot.ts`) — nothing here is displayed.
 *
 *   bun compositions/fit/gen.ts spec.json
 */

export const VIEW = { w: 1920, h: 4320 } as const;

export interface Block {
  /** Content. May contain '\n' — the core's only break. */
  readonly text: string;
  /** Utilities on the `Text`, e.g. `text-[38px] font-bold`. */
  readonly cls: string;
  /** Box width in px — the thing the text is supposed to fit. */
  readonly w: number;
  /** Box height in px. */
  readonly h: number;
  /** Extra utilities on the box itself, e.g. `overflow-hidden`. */
  readonly boxCls?: string;
  /** Draw the box as a white rectangle and no text (geometry check). */
  readonly fill?: boolean;
}

export interface Spec {
  readonly blocks: readonly Block[];
}

/** Vertical band each block occupies, from stacking order alone. */
export function bands(spec: Spec): { readonly y0: number; readonly y1: number }[] {
  let y = 0;
  return spec.blocks.map((b) => {
    const y0 = y;
    y += b.h;
    return { y0, y1: y };
  });
}

export function source(spec: Spec): string {
  const total = spec.blocks.reduce((a, b) => a + b.h, 0);
  if (total > VIEW.h) {
    throw new Error(`fit: blocks total ${total}px, viewport is ${VIEW.h}px`);
  }
  const blocks = spec.blocks.map((b) => {
    const box = `w-[${b.w}px] h-[${b.h}px] flex-col${b.boxCls ? ` ${b.boxCls}` : ""}`;
    return b.fill
      ? `      <View class="w-[${b.w}px] h-[${b.h}px] bg-white" />`
      : `      <View class="${box}">\n` +
        `        <Text class="${b.cls}">{${JSON.stringify(b.text)}}</Text>\n` +
        `      </View>`;
  });
  return `// GENERATED by compositions/fit/gen.ts — do not edit.
//
// Fixed boxes stacked top-left, no padding, no gap: block i starts at the sum
// of the heights before it. Ground black, text white, so any non-black pixel is
// ink and ink outside a box is overflow.

import { Text, View } from "@pocketjs/framework/components";

export default function Fit() {
  return (
    <View class="w-full h-full bg-black flex-col">
${blocks.join("\n")}
    </View>
  );
}
`;
}

if (import.meta.main) {
  const path = process.argv[2];
  if (!path) {
    console.error("usage: gen.ts <spec.json>");
    process.exit(2);
  }
  const spec = (await Bun.file(path).json()) as Spec;
  await Bun.write(new URL("./app.tsx", import.meta.url).pathname, source(spec));
  console.log(`fit: ${spec.blocks.length} block(s)`);
}
