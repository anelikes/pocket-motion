#!/usr/bin/env bun
/**
 * Four host-driven clip placements on one clock, from one table.
 *
 *   bun compositions/footage-tracks/gen.ts
 *
 * This generator writes BOTH `app.tsx` and `pocket-motion.json`, because the
 * two halves of a footage declaration are one fact written twice. The sidecar
 * says `grid`; the tree says how wide each tile is drawn. `openFootage` derives
 * the grid from the tree with `gridOf` and refuses the track when the two
 * disagree — and the drawn size IS the ingested size, so a hand edit to one
 * side stretches the picture rather than failing. Deriving both from `PANELS`
 * below is what keeps them from being edited apart.
 *
 * What each panel is here to exercise, stated once:
 *
 * - `wide-open` and `wide-return` are the SAME clip in two windows, which is
 *   the whole reason `sourceFrame` exists: the second window opens on clip
 *   frame 89 rather than 0, so a mapping bug shows as the wrong picture rather
 *   than as an absent one. That clip is 24 fps and the composition is 30, so
 *   the ingest resamples rather than copying frame for frame.
 * - `portrait-cover` draws a 9:16 source into a 4:3 box. Drop its `fit` and
 *   `openFootage` refuses before it pays for the ingest, naming the drift a
 *   bare scale would apply: `moving the far edge by 278 px`.
 * - `wide-contain` draws a 2:1 source into a 20:9 box — 80 px, the smaller of
 *   the two mismatches and still far over the one-pixel rounding floor.
 *
 * The panels tile the frame edge to edge and do not overlap, so every tile
 * contributes pixels and `visibility` has nothing to report. That is a
 * property of this layout, not of footage: `compositions/occluded` is where a
 * buried node is the point.
 */

import { join } from "node:path";

import { footageTrack, tileNodes } from "../../src/footage/declare.ts";
import { gridOf } from "../../src/footage/tiling.ts";
import { TEX_MAX_DIM } from "../../src/manifest/sidecar.ts";

const DIR = new URL(".", import.meta.url).pathname.replace(/\/$/, "");

export const VIEW = { w: 1280, h: 720 } as const;
export const FPS = 30;
export const DURATION_FRAMES = 150;
export const TILE = TEX_MAX_DIM;

export interface Panel {
  /** Track id, node prefix suffix, and the label drawn over the panel. */
  readonly id: string;
  readonly src: string;
  /** Where the panel sits in the frame. The tiles below are panel-relative. */
  readonly box: { readonly x: number; readonly y: number; readonly w: number; readonly h: number };
  readonly startFrame: number;
  readonly endFrame: number;
  readonly sourceFrame: number;
  /** Absent means the source's aspect already matches `box`. */
  readonly fit?: "cover" | "contain" | "stretch";
  readonly label: string;
}

export const PANELS: readonly Panel[] = [
  {
    id: "wide-open",
    src: "assets/synthetic/bars-16x9-24fps.mp4",
    box: { x: 0, y: 0, w: 640, h: 360 },
    startFrame: 0,
    endFrame: 60,
    sourceFrame: 0,
    label: "wide-open  frames 0-60  sourceFrame 0  no fit",
  },
  {
    id: "wide-return",
    src: "assets/synthetic/bars-16x9-24fps.mp4",
    box: { x: 640, y: 0, w: 640, h: 360 },
    startFrame: 60,
    endFrame: 150,
    sourceFrame: 89,
    label: "wide-return  frames 60-150  sourceFrame 89  same clip",
  },
  {
    id: "portrait-cover",
    src: "assets/synthetic/bars-9x16-30fps.mp4",
    box: { x: 0, y: 360, w: 480, h: 360 },
    startFrame: 0,
    endFrame: 150,
    sourceFrame: 0,
    fit: "cover",
    label: "portrait-cover  9:16 into 4:3  fit cover",
  },
  {
    id: "wide-contain",
    src: "assets/synthetic/wide-2x1-30fps.mp4",
    box: { x: 480, y: 360, w: 800, h: 360 },
    startFrame: 0,
    endFrame: 89,
    sourceFrame: 0,
    fit: "contain",
    label: "wide-contain  2:1 into 20:9  fit contain",
  },
];

const prefixOf = (p: Panel): string => `footage:${p.id}`;

/** One `<Image>` per tile, panel-relative, inside one positioned wrapper. */
function panelSource(p: Panel): string {
  const tiles = tileNodes({
    nodePrefix: prefixOf(p),
    width: p.box.w,
    height: p.box.h,
    tile: TILE,
    indent: "        ",
  });
  // The label is a sibling AFTER the tiles: document order decides paint
  // order, so a caption declared before the footage it annotates is painted
  // under it (`compositions/occluded`).
  const label =
    `        <Text debugName="label:${p.id}" ` +
    `class="absolute left-[16px] top-[16px] text-[20px] font-bold text-[#f8fafc]">` +
    `{${JSON.stringify(p.label)}}</Text>`;
  return (
    `      <View class="absolute left-[${p.box.x}px] top-[${p.box.y}px] ` +
    `w-[${p.box.w}px] h-[${p.box.h}px]">\n${tiles}\n${label}\n      </View>`
  );
}

export function source(): string {
  return `// GENERATED by compositions/footage-tracks/gen.ts — do not edit.

import { Image, Text, View } from "@pocketjs/framework/components";

export default function FootageTracks() {
  return (
    <View class="w-full h-full bg-[#05070a]">
${PANELS.map(panelSource).join("\n")}
    </View>
  );
}
`;
}

export function sidecar(): string {
  return (
    JSON.stringify(
      {
        motion: 1,
        durationFrames: DURATION_FRAMES,
        fps: FPS,
        supersample: 1,
        footage: PANELS.map((p) =>
          footageTrack({
            id: p.id,
            src: p.src,
            nodePrefix: prefixOf(p),
            tile: TILE,
            width: p.box.w,
            height: p.box.h,
            startFrame: p.startFrame,
            endFrame: p.endFrame,
            sourceFrame: p.sourceFrame,
            ...(p.fit ? { fit: p.fit } : {}),
          }),
        ),
        fonts: {
          regular: "assets/fonts/HarmonyOS_Sans_Regular.ttf",
          bold: "assets/fonts/HarmonyOS_Sans_Bold.ttf",
        },
      },
      null,
      2,
    ) + "\n"
  );
}

if (import.meta.main) {
  await Bun.write(join(DIR, "app.tsx"), source());
  await Bun.write(join(DIR, "pocket-motion.json"), sidecar());
  const tiles = PANELS.reduce((n, p) => {
    const [c, r] = gridOf(p.box.w, p.box.h, TILE);
    return n + c * r;
  }, 0);
  console.error(
    `footage-tracks: ${PANELS.length} track(s) over ${new Set(PANELS.map((p) => p.src)).size} ` +
      `clip(s), ${tiles} tile(s), ${DURATION_FRAMES} frames at ${FPS} fps`,
  );
}
