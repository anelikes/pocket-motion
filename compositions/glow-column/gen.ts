#!/usr/bin/env bun
/**
 * The column veil, rendered — two stacks side by side from the same
 * `glowColumnNodes` the copy and lower-third generators emit.
 *
 * The templates pin that emission as a string. What a string cannot reach is
 * whether `rotate-180` turns the lower cap over in the picture: dropping it
 * leaves the bright edge at the bottom and a dark seam under the last row,
 * and every assertion about the source still passes. This composition is in
 * the digest ledger, so that change moves a recorded number.
 *
 * The right stack is 656px — past the 512 the fill used to be clamped at —
 * so the ledger also covers the case where the falloff once ate the last row.
 *
 *   bun compositions/glow-column/gen.ts
 *   bun src/cli/main.ts render compositions/glow-column --out out.mp4
 */

import { mkdir } from "node:fs/promises";
import { join, resolve } from "node:path";

import { glowColumnNodes, writeGlowColumn } from "../../src/image/glow.ts";

const DIR = new URL(".", import.meta.url).pathname;

export const COLUMN = 720;
/** `gap-4`. Row heights are explicit so the stack height needs no measurer. */
export const GAP = 16;
export const SHORT_ROWS = [80, 44] as const;
export const TALL_ROWS = [96, 64, 64, 64, 64, 64, 64, 64] as const;

export function stackHeight(rows: readonly number[]): number {
  return rows.reduce((a, b) => a + b, 0) + GAP * (rows.length - 1);
}

function column(left: number, rows: readonly number[], label: string): string {
  const stackH = stackHeight(rows);
  const body = rows
    .map(
      (h, i) =>
        `          <View class="w-[${COLUMN}px] h-[${h}px] justify-center">\n` +
        `            <Text class="text-[${i === 0 ? 40 : 28}px] text-[#f8fafc]">{${JSON.stringify(
          i === 0 ? label : `${label} · 第 ${i} 行`,
        )}}</Text>\n` +
        `          </View>`,
    )
    .join("\n");
  return (
    // One `absolute` does both jobs: it places the column and it is the
    // containing block the glow Images position against.
    `      <View class="absolute left-[${left}px] top-[200px] w-[${COLUMN}px] flex-col gap-4">\n` +
    glowColumnNodes(COLUMN, stackH, "        ") +
    `${body}\n` +
    `      </View>`
  );
}

export function source(): string {
  return `// GENERATED by compositions/glow-column/gen.ts — do not edit.
//
// Both columns come from glowColumnNodes(), the same emitter copy and
// lower-third use. The right stack is taller than 512 on purpose.

import { Image, Text, View } from "@pocketjs/framework/components";

export default function GlowColumn() {
  return (
    <View class="w-full h-full bg-[#020617] relative">
${column(120, SHORT_ROWS, "短栈")}
${column(1080, TALL_ROWS, "高栈")}
    </View>
  );
}
`;
}

export async function generate(outDir: string = DIR): Promise<void> {
  await writeGlowColumn(outDir);
  await Bun.write(join(outDir, "app.tsx"), source());
}

if (import.meta.main) {
  const outDir = resolve(DIR);
  await mkdir(outDir, { recursive: true });
  await generate(outDir);
  console.log(
    `glow-column: wrote ${join(outDir, "app.tsx")} — stacks ${stackHeight(SHORT_ROWS)} and ${stackHeight(TALL_ROWS)}`,
  );
}
