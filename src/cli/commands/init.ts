/**
 * `init <dir> --example smoke|copy|footage-tracks|sound-roles`
 * Question: what is the smallest complete composition I can start from, and
 * what do I run next?
 *
 * A composition is six or seven small files that have to agree with each
 * other — `pocket.json`'s viewport with the sidecar's `supersample`, the
 * sidecar's `fonts` with the build command every command prints, a generator's
 * output with the sources committed beside it. Starting from a blank
 * directory means getting all of that right before anything can tell you
 * whether you got it right, and the first thing that speaks up is a build
 * three layers down. Starting from a fixture that already passes means the
 * first failure is about the change you made.
 *
 * WHAT IS COPIED: the fixture's TRACKED files, minus `app.tsx` when there is
 * a `gen.ts` beside it — that file is generated, carries a
 * `// GENERATED by …` header, and copying it would seed the new composition
 * with output whose generator has not run. `dist` is not in the tracked set
 * at all, so it cannot come along.
 *
 * WHERE IT MAY WRITE, and why the boundary is there rather than anywhere:
 * **inside this repository's `compositions/` tree.** Three separate
 * mechanisms make a composition a resident of this tree rather than a
 * portable directory —
 *
 *   - a generator reaches shared code by a path relative to the repository
 *     (`../../src/footage/tiling.ts`), which is a path only a directory in
 *     this tree has;
 *   - a generator derives the repository root from its own location
 *     (`new URL("../..", import.meta.url)`), and uses it to find the faces;
 *   - the sidecar's `fonts` and `footage[].src` are repo-relative and are
 *     resolved against `repoRootOf`, which is the nearest `compositions/`
 *     ancestor.
 *
 * — so a directory outside the tree would need all three rewritten to
 * absolute paths into this checkout, which is not a starting point, it is a
 * copy welded to one machine. The refusal names `compositions/<name>`.
 *
 * DEPTH IS handled, because nesting is real (`compositions/nested/a/9x16`): a
 * relative specifier that ESCAPES the composition directory is re-resolved
 * against the destination, so `../../src/x.ts` becomes `../../../src/x.ts`
 * one level deeper. A specifier that does not escape — `./app.tsx`,
 * `new URL(".", import.meta.url)` — is left exactly as it is, because it
 * means "beside me" and that is still true. At equal depth every source is
 * copied byte for byte.
 *
 * WHAT IT REFUSES RATHER THAN PAPERING OVER: an existing non-empty directory,
 * and an asset the sidecar names that is not on disk. The second matters
 * because it is the one thing copying cannot fix — the CJK faces and the
 * synthetic clips are fetched, not tracked — and a composition whose fonts
 * are missing fails much later, inside `resolveComposition`, about a path the
 * author never typed.
 */

import { existsSync, readdirSync, statSync } from "node:fs";
import { mkdirSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";

import { parseSidecar, type MotionSidecar } from "../../manifest/sidecar.ts";
import { UsageError, optionalString, parseArgs, requirePositional } from "../args.ts";
import { EXIT_OK, EXIT_USAGE, type CommandResult } from "../types.ts";

/** The repository root — this module sits at `src/cli/commands/`. */
const ROOT = resolve(import.meta.dir, "../../..");

/** The fixtures `--example` names, and what each is for. */
export const EXAMPLES: Readonly<Record<string, string>> = {
  smoke: "no generator, no assets — the smallest thing that builds and traces",
  copy: "a title card whose line breaks are measured at build time (CJK faces)",
  "footage-tracks": "four windows over three clips: sourceFrame, cover, contain",
  "sound-roles": "one element of each sound role, over a footage track",
};

export const EXAMPLE_NAMES = Object.keys(EXAMPLES);

/** Files copied verbatim rather than rewritten. Everything else is text. */
function isBinary(name: string): boolean {
  return /\.(png|jpg|jpeg|webp|ttf|otf|wav|mp3|mp4|pak)$/i.test(name);
}

/** Tracked files of a composition directory, relative to it. */
async function trackedFiles(dir: string): Promise<string[]> {
  const proc = Bun.spawn(["git", "ls-files", "--cached", "--", dir], {
    cwd: ROOT,
    stdout: "pipe",
    stderr: "pipe",
  });
  const [out, code] = await Promise.all([new Response(proc.stdout).text(), proc.exited]);
  if (code !== 0) throw new Error(`git ls-files failed in ${dir}`);
  return out
    .split("\n")
    .filter(Boolean)
    .map((p) => relative(dir, join(ROOT, p)))
    .filter((p) => !p.startsWith(".."))
    .sort();
}

/**
 * Re-resolve one relative specifier written in `fromDir` so it means the same
 * file from `toDir`. Returns null when the specifier does not escape its own
 * directory and so needs no change.
 */
export function rebaseSpecifier(
  specifier: string,
  fromDir: string,
  toDir: string,
): string | null {
  if (!specifier.startsWith("../")) return null;
  const target = resolve(fromDir, specifier);
  let rebased = relative(toDir, target);
  if (rebased === "") rebased = ".";
  if (!rebased.startsWith(".")) rebased = `./${rebased}`;
  // A trailing separator in the original ("../../") is meaningful to
  // `new URL`, which reads it as a directory; keep it.
  if (specifier.endsWith("/") && !rebased.endsWith("/")) rebased = `${rebased}/`;
  return rebased === specifier ? null : rebased;
}

/**
 * Every rewrite one copied text file gets.
 *
 * Two of them, and they do not overlap: relative specifiers that escape the
 * composition directory are re-resolved for the new depth, and the fixture's
 * own repo-relative path is replaced wherever it is spelled out — which is
 * how the doc comments (`bun compositions/copy/gen.ts`) and a generator's
 * `// GENERATED by …` header end up naming the new composition instead of the
 * one it was copied from.
 */
export function rewriteSource(
  text: string,
  options: {
    readonly fromDir: string;
    readonly toDir: string;
    readonly fromRel: string;
    readonly toRel: string;
  },
): string {
  let out = text.replace(
    /(['"`])(\.\.\/[^'"`\n]*)\1/g,
    (whole, quote: string, spec: string) => {
      const rebased = rebaseSpecifier(spec, options.fromDir, options.toDir);
      return rebased === null ? whole : `${quote}${rebased}${quote}`;
    },
  );
  // Not followed by a path character, so `compositions/copy` does not match
  // inside `compositions/copy-of-something`.
  const escaped = options.fromRel.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  out = out.replaceAll(new RegExp(`${escaped}(?![A-Za-z0-9_-])`, "g"), options.toRel);
  return out;
}

/** `compositions/a/b` → `a-b`; the stem for ids and artifact names. */
export function slugOf(relToCompositions: string): string {
  return relToCompositions.split("/").join("-");
}

/**
 * `pocket.json` for the new composition.
 *
 * The identity fields are re-derived rather than copied. Two compositions
 * sharing a `compositionId` is a real state in this tree and a confusing one:
 * preview's rail is keyed by PATH precisely because of it. A fixture copied
 * out under a new name should not add another pair.
 */
export function rewritePocketJson(text: string, toRel: string): string {
  const manifest = JSON.parse(text) as Record<string, unknown>;
  const slug = slugOf(toRel);
  manifest.id = `dev.pocket-stack.motion-${slug}`;
  manifest.name = `pocketjs-motion-${slug}`;
  manifest.title = `PocketJS Motion: ${slug}`;
  const app = manifest.app as Record<string, unknown> | undefined;
  if (app) {
    app.entry = `compositions/${toRel}/main.tsx`;
    app.output = `motion-${slug}`;
  }
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/** Every repo-relative file the sidecar names — fonts, footage, sound. */
export function declaredAssets(sidecar: MotionSidecar): string[] {
  const out: string[] = [];
  if (sidecar.fonts) out.push(sidecar.fonts.regular, sidecar.fonts.bold);
  for (const track of sidecar.footage) out.push(track.src);
  const sound = sidecar.sound;
  if (sound) {
    if (sound.bed) out.push(sound.bed.src);
    for (const role of [sound.narration, sound.dialogue, sound.cues]) {
      for (const element of role ?? []) out.push(element.src);
    }
  }
  return [...new Set(out)].sort();
}

export interface InitOptions {
  readonly dir: string;
  readonly example: string | undefined;
  /** `process.stdout.isTTY`, injected so the non-TTY branch is testable. */
  readonly tty: boolean;
}

function exampleList(): string[] {
  return EXAMPLE_NAMES.map((name) => `  ${name.padEnd(15)} ${EXAMPLES[name]}`);
}

export async function run(options: InitOptions): Promise<CommandResult> {
  if (options.example === undefined) {
    // Both branches exit 2 — the invocation was incomplete either way. What
    // differs is who is reading: a person gets the menu, a script gets told
    // which flag it forgot.
    const lines = options.tty
      ? ["init needs an example to start from:", ...exampleList()]
      : [
          "init requires --example when stdout is not a terminal; there is nothing to " +
            "prompt on. One of:",
          ...exampleList(),
        ];
    return {
      exitCode: EXIT_USAGE,
      json: { ok: false, error: lines[0], examples: EXAMPLES },
      // The menu IS the message, so it goes to stdout alone; repeating the
      // first line on stderr printed it twice in a terminal.
      stdoutLines: lines,
    };
  }
  if (!(options.example in EXAMPLES)) {
    throw new UsageError(
      `unknown example ${JSON.stringify(options.example)} — one of ${EXAMPLE_NAMES.join(", ")}`,
    );
  }

  const dest = resolve(options.dir);
  const compositionsRoot = join(ROOT, "compositions");
  const toRel = relative(compositionsRoot, dest);
  if (toRel === "" || toRel.startsWith("..") || toRel.split(sep).includes("dist")) {
    throw new UsageError(
      `init writes inside this repository's compositions/ tree; ${dest} is not in it.\n` +
        "A composition is a resident of this tree rather than a portable directory: its\n" +
        "generator imports shared code by a path relative to the repository, derives the\n" +
        "repository root from its own location, and its sidecar names fonts and clips\n" +
        "repo-relative. Try:\n" +
        `  bun src/cli/main.ts init compositions/<name> --example ${options.example}`,
    );
  }

  if (existsSync(dest)) {
    if (!statSync(dest).isDirectory()) {
      throw new UsageError(`${dest} exists and is not a directory`);
    }
    const entries = readdirSync(dest);
    if (entries.length > 0) {
      throw new UsageError(
        `${dest} already exists and is not empty (${entries.length} entr${entries.length === 1 ? "y" : "ies"}: ` +
          `${entries.slice(0, 5).join(", ")}${entries.length > 5 ? ", …" : ""}).\n` +
          "init writes a whole composition and will not merge into one that is already " +
          "there. Name a new directory, or empty this one first.",
      );
    }
  }

  const fromRel = options.example;
  const fromDir = join(compositionsRoot, fromRel);
  const files = await trackedFiles(fromDir);
  const hasGenerator = files.includes("gen.ts");

  // The sidecar's assets are the one thing copying cannot supply: the CJK
  // faces and the synthetic clips are fetched, not tracked. Asked BEFORE
  // anything is written, so a refusal leaves no half-composition behind.
  const sidecarRaw = (await Bun.file(join(fromDir, "pocket-motion.json")).json()) as unknown;
  const parsed = parseSidecar(sidecarRaw);
  if (!parsed.ok) {
    throw new UsageError(
      `the ${fromRel} fixture's own sidecar does not parse; this is a bug in the fixture, ` +
        `not in your invocation:\n  ${parsed.diagnostics.map((d) => `${d.path || "/"}: ${d.code}`).join("\n  ")}`,
    );
  }
  const missing = declaredAssets(parsed.value).filter((rel) => !existsSync(join(ROOT, rel)));
  if (missing.length > 0) {
    throw new UsageError(
      `${fromRel} declares ${missing.length} file(s) that are not on disk, so the copy would ` +
        "not build:\n" +
        missing.map((m) => `  ${m}`).join("\n") +
        "\nThese are fetched rather than tracked. Get them with:\n  bun scripts/assets.ts",
    );
  }

  const written: string[] = [];
  for (const name of files) {
    if (name === "app.tsx" && hasGenerator) continue;
    const src = join(fromDir, name);
    const out = join(dest, name);
    mkdirSync(dirname(out), { recursive: true });
    if (isBinary(name)) {
      await Bun.write(out, Bun.file(src));
    } else if (name === "pocket.json") {
      await Bun.write(out, rewritePocketJson(await Bun.file(src).text(), toRel));
    } else {
      await Bun.write(
        out,
        rewriteSource(await Bun.file(src).text(), {
          fromDir,
          toDir: dest,
          fromRel: `compositions/${fromRel}`,
          toRel: `compositions/${toRel}`,
        }),
      );
    }
    written.push(name);
  }

  const dirArg = relative(ROOT, dest) || dest;
  const next: string[] = [];
  if (hasGenerator) {
    next.push(`bun ${dirArg}/gen.ts`);
  }
  next.push(
    `bun src/cli/main.ts build ${dirArg}`,
    `bun src/cli/main.ts lint ${dirArg}`,
    `bun src/cli/main.ts check ${dirArg}`,
    `bun src/cli/main.ts trace ${dirArg}`,
  );

  const stdoutLines = [
    `init ok — ${written.length} file(s) from compositions/${fromRel} into ${dirArg}`,
    ...written.map((n) => `  ${n}`),
    "",
    "Next:",
    ...next.map((c) => `  ${c}`),
    "",
    "Then account for it in both ledgers — each refuses to run until every composition",
    "in the tree is either measured or excused with a written reason:",
    "  scripts/digests.ts ENTRIES / EXEMPT",
    "  scripts/visibility.ts EXEMPT",
  ];
  if (hasGenerator) {
    stdoutLines.splice(
      1 + written.length,
      0,
      "",
      `app.tsx was not copied: ${fromRel} generates it, and seeding a new composition with ` +
        "output whose generator has not run is how a hand edit to a generated file starts.",
    );
  }

  return {
    exitCode: EXIT_OK,
    json: {
      ok: true,
      example: fromRel,
      dir: dest,
      files: written,
      generated: hasGenerator ? ["app.tsx"] : [],
      next,
    },
    stdoutLines,
  };
}

export async function runFromArgv(argv: readonly string[]): Promise<CommandResult> {
  const parsed = parseArgs(["init", ...argv]);
  const dir = requirePositional(parsed.positionals, 0, "target-dir");
  return run({
    dir,
    example: optionalString(parsed.flags, "example"),
    tty: process.stdout.isTTY === true,
  });
}
