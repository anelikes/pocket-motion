/**
 * A footage tile name written by hand.
 *
 * `<nodePrefix>/tile:<col>:<row>` is a PROTOCOL, not an authoring vocabulary.
 * The host builds that string to find the node it uploads pixels into
 * (`FootageLayer.create`), matches on its prefix to read the drawn size out of
 * the tree (`pictureSizeFromTree`), and derives the sidecar's `grid` from the
 * same geometry. An author writing the name themselves is writing a string
 * that has to agree with three things at once, and the drawn size IS the
 * ingested size — so getting it consistently wrong stretches the picture
 * rather than failing.
 *
 * `tileNodes` (`src/footage/declare.ts`) is the one way to declare them. This
 * finds the ones that did not come from it.
 *
 * ── WHAT IT LOOKS AT, and why it is narrower than "any tile-shaped name" ───
 *
 * Only names that begin with a `nodePrefix` the SIDECAR DECLARES. A tile name
 * matters because the host will bind it; a composition that declares no
 * footage has no protocol to violate, and its tile-shaped names are a private
 * arrangement with whatever is pushing the textures. Two fixtures in this tree
 * are exactly that — `compositions/kenburns` and `compositions/shimmer` draw
 * `footage:kb/tile:…` and `footage:probe/tile:…` and declare no `footage` at
 * all, because `scripts/push-probe.ts` and `scripts/shimmer-probe.ts` push
 * their pixels directly. Warning on those would be advice to call `tileNodes`,
 * which for `shimmer` is WRONG: it draws each tile at an arbitrary `cell` size
 * to vary the minification ratio, which is the one thing `tileNodes` will not
 * do, because for a bound track the drawn size has to be the ingested size.
 *
 * Within the composition directory's own `.ts` / `.tsx` files — the same list
 * `lint` already reads — it looks only inside string and template literals,
 * using `classifyRegions` from the mount-only lint rather than a second
 * scanner of its own, so a tile name in a comment is prose and is ignored.
 *
 * A file is CLEAN when it is generated and its generator is clean:
 * specifically, when its head carries `GENERATED by <path>/gen.ts`, that
 * `gen.ts` is in the same directory, and the generator holds no declared tile
 * name in a literal of its own. That excuse is narrow on purpose — a
 * generator that builds the name itself, with a template or with
 * concatenation, still carries it in a literal and is still reported, on its
 * own line. `tileNodes` puts the name in `src/`, where a generator cannot
 * hold it.
 *
 * ── WHAT IT CANNOT SEE, and says so in the message ─────────────────────────
 *
 * It does not run generators, does not resolve imports, and does not look at
 * the rendered tree. A name assembled out of pieces that are individually not
 * a tile name — `"/tile" + ":"` — is invisible to it, and so is one produced
 * by a module outside the composition directory. That is why it warns rather
 * than fails: it is a claim about what the source text says, not about what
 * the composition does, and `openFootage` is what refuses a track whose tiles
 * are actually absent or the wrong size.
 */

import { TILE_NAME_INFIX, tileNamePrefix } from "../footage/tiling.ts";
import { classifyRegions } from "./mount-only.ts";

export const CODE_TILE_NAMED_BY_HAND = "footage.tileNamedByHand";

export interface TileWarning {
  readonly code: typeof CODE_TILE_NAMED_BY_HAND;
  readonly file: string;
  readonly line: number;
  readonly column: number;
  readonly message: string;
}

/**
 * Byte offsets at which a DECLARED track's tile name occurs inside a string or
 * template literal.
 *
 * Literal regions only: `classifyRegions` marks a template's interpolations as
 * code and its text as string, so `` `${prefix}/tile:${c}:${r}` `` is found at
 * the `/tile:` in the text — which is the hand-rolled case — as long as some
 * declared prefix makes that text a tile name. A template whose prefix is
 * interpolated is matched on the infix alone, since the prefix is not in the
 * text to compare.
 */
export function tileNameOffsets(
  source: string,
  nodePrefixes: readonly string[],
): number[] {
  if (nodePrefixes.length === 0) return [];
  const kind = classifyRegions(source);
  const out: number[] = [];
  let from = 0;
  for (;;) {
    const at = source.indexOf(TILE_NAME_INFIX, from);
    if (at === -1) break;
    from = at + 1;
    if (kind[at] !== "string") continue;
    // Either the declared prefix is spelled out right before the infix, or the
    // infix follows an interpolation — the `${prefix}/tile:` shape a
    // hand-rolling generator writes, where the prefix is not in the text to
    // compare against. `classifyRegions` marks the `}` closing a `${` as
    // string and the expression inside it as code, so the pair identifies it
    // exactly rather than by guessing at the character.
    const spelled = nodePrefixes.some((p) => source.startsWith(tileNamePrefix(p), at - p.length));
    const afterInterpolation =
      at >= 2 && source[at - 1] === "}" && kind[at - 2] === "code";
    if (spelled || afterInterpolation) out.push(at);
  }
  return out;
}

/** The generator a `// GENERATED by <path> — do not edit.` header names. */
export function generatedBy(source: string): string | null {
  // The first few lines only: this is a HEADER, and every generated file in
  // this tree puts it on line 1. Scanning the whole file would match a
  // sentence about generated files inside one that is not.
  const head = source.split("\n", GENERATED_HEADER_LINES).join("\n");
  const match = /GENERATED by ([\w./-]+)/.exec(head);
  return match ? match[1]! : null;
}

/** How far into a file the `GENERATED by` header may sit. */
export const GENERATED_HEADER_LINES = 5;

function indexToLineCol(source: string, index: number): { line: number; column: number } {
  let line = 1;
  let column = 1;
  for (let i = 0; i < index && i < source.length; i++) {
    if (source.charCodeAt(i) === 10) {
      line++;
      column = 1;
    } else {
      column++;
    }
  }
  return { line, column };
}

export interface TileLintFile {
  /** Absolute path, for the message. */
  readonly file: string;
  /** File name within the composition directory, e.g. `app.tsx`. */
  readonly name: string;
  readonly text: string;
}

/** What this lint cannot see, appended to every message it produces. */
const REACH =
  "This reads the composition directory's sources as text and looks only inside string " +
  "and template literals, for names beginning with a nodePrefix the sidecar declares. It " +
  "does not run generators, resolve imports, or look at the rendered tree, so it is a " +
  "warning rather than an error: `openFootage` is what refuses a track whose tiles are " +
  "actually absent or the wrong size.";

/**
 * Warn for every declared tile name this cannot attribute to a `tileNodes`
 * call.
 *
 * Takes the whole directory at once rather than one file, because the excuse
 * is a relationship between two files: a generated `app.tsx` is clean only
 * because the `gen.ts` beside it is. And when it is not, the warning lands on
 * the GENERATOR — that is where the fix goes, and reporting both would be two
 * lines about one edit.
 */
export function lintTileNames(
  files: readonly TileLintFile[],
  nodePrefixes: readonly string[],
): TileWarning[] {
  if (nodePrefixes.length === 0) return [];
  const byName = new Map(files.map((f) => [f.name, f]));
  const offsetsOf = new Map(files.map((f) => [f.name, tileNameOffsets(f.text, nodePrefixes)]));

  /** Generators in this directory that some generated file here points at. */
  const generators = new Set<string>();
  for (const file of files) {
    const named = generatedBy(file.text);
    if (named === null) continue;
    const genName = named.split("/").at(-1)!;
    if (byName.has(genName)) generators.add(genName);
  }

  const warnings: TileWarning[] = [];
  for (const file of files) {
    const offsets = offsetsOf.get(file.name)!;
    if (offsets.length === 0) continue;

    const named = generatedBy(file.text);
    if (named !== null) {
      const genName = named.split("/").at(-1)!;
      const gen = byName.get(genName);
      if (gen !== undefined) {
        // Either the generator is clean, in which case the names came from
        // the only other thing that emits them, or it is not, in which case
        // it is reported on its own visit below. Either way, not here.
        continue;
      }
    }

    const at = indexToLineCol(file.text, offsets[0]!);
    const message = generators.has(file.name)
      ? `this generator builds a footage tile name itself (${offsets.length} occurrence(s)). ` +
        `The shape \`<nodePrefix>${TILE_NAME_INFIX}<col>:<row>\` is the protocol the host uses ` +
        "to find the node it uploads pixels into, and it has to agree with the sidecar's " +
        "`grid` and with each tile's drawn size at the same time. Emit the nodes with " +
        "`tileNodes` from `src/footage/declare.ts` and the sidecar entry with `footageTrack` " +
        `beside it; both derive from one width and height.\n${REACH}`
      : `${offsets.length} footage tile name(s) written here by hand. The shape ` +
        `\`<nodePrefix>${TILE_NAME_INFIX}<col>:<row>\` is the protocol the host uses to find ` +
        "the node it uploads pixels into; it has to agree with the sidecar's `grid` and with " +
        "each tile's drawn `w-[Npx] h-[Npx]`, and because the drawn size IS the ingested " +
        "size, getting all three consistently wrong stretches the picture instead of " +
        "failing. Generate them with `tileNodes` from `src/footage/declare.ts` and the " +
        `sidecar entry with \`footageTrack\` beside it.\n${REACH}`;

    warnings.push({
      code: CODE_TILE_NAMED_BY_HAND,
      file: file.file,
      line: at.line,
      column: at.column,
      message,
    });
  }
  return warnings;
}
